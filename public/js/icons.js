/** Élément SVG d'une icône ; un nom inconnu donne un élément vide plutôt qu'une erreur. */
export function icon(name, size = 20, strokeWidth = 2) {
  if (!Object.prototype.hasOwnProperty.call(PATHS, name)) return document.createElement("span");
  const tpl = document.createElement("template");
  tpl.innerHTML =
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" ` +
    `aria-hidden="true" focusable="false">${PATHS[name]}</svg>`;
  return tpl.content.firstChild;
}

/** Remplace chaque <span data-icon="nom" data-size="18"> de la page par son icône. */
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((slot) => {
    const svg = icon(slot.dataset.icon, Number(slot.dataset.size) || 20, Number(slot.dataset.stroke) || 2);
    slot.replaceChildren(svg);
  });
}

